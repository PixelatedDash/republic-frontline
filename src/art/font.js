export const FONT7 = { glyphs: G7, h: 7, spacing: 1 };
export const FONT5 = { glyphs: G5, h: 5, spacing: 1 };

function glyph(font, ch) {
  return font.glyphs[ch] || font.glyphs[ch.toUpperCase()] || font.glyphs['?'] || font.glyphs[' '];
}

export function measure(text, font = FONT7) {
  let w = 0;
  for (const ch of text) w += glyph(font, ch)[0].length + font.spacing;
  return Math.max(0, w - font.spacing);
}

// Draw text into a bitmap. Options: color, shadow (hex, drawn +1,+1), outline (hex).
export function drawText(bm, text, x, y, { color = '#e6ece9', shadow = null, outline = null, font = FONT7 } = {}) {
  const w = measure(text, font) + 2;
  const layer = new Bitmap(w, font.h + 2);
  const c = rgba(color);
  let cx = 1;
  for (const ch of text) {
    const g = glyph(font, ch);
    for (let j = 0; j < g.length; j++)
      for (let i = 0; i < g[j].length; i++) if (g[j][i] === '#') layer.set(cx + i, 1 + j, c);
    cx += g[0].length + font.spacing;
  }
  if (outline) {
    const o = rgba(outline);
    const base = layer.clone();
    for (let j = 0; j < layer.h; j++)
      for (let i = 0; i < layer.w; i++) {
        if (base.get(i, j)) continue;
        if (base.get(i - 1, j) || base.get(i + 1, j) || base.get(i, j - 1) || base.get(i, j + 1)) layer.set(i, j, o);
      }
  }
  if (shadow) {
    const s = rgba(shadow);
    const sh = new Bitmap(layer.w, layer.h);
    for (let i = 0; i < layer.d.length; i++) if (layer.d[i]) sh.d[i] = s;
    blit(bm, sh, x - 1, y);
  }
  blit(bm, layer, x - 1, y - 1);
  return measure(text, font);
}
