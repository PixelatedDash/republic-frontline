// Balance gates (spec §19), one level per process so they run in parallel:
//   node tools/sim/report.mjs --level geonosis-3        -> JSON line
//   node tools/sim/report.mjs --write results/*.json    -> BALANCE_REPORT.md
// Gates: balanced wins every level on Padawan and >= 1/5 seeds on Jedi;
// every spam-<tower> bot loses every level from Geonosis 3 on (Jedi, all
// seeds); no-upgrades loses every boss level on Jedi.

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { createSim, runToEnd } from '../../src/sim/sim.js';
import { LEVELS, LEVEL_ORDER } from '../../src/data/levels/index.js';
import { TOWERS } from '../../src/data/towers.js';
import { STRENGTH } from '../../src/data/balance.js';
import { makeBot } from './bots.mjs';

const SEEDS = 5;
const SPAM_FROM = LEVEL_ORDER.indexOf('geonosis-3');

function runSet(level, difficulty, bot) {
  const rows = [];
  for (let seed = 1; seed <= SEEDS; seed++) {
    const s = runToEnd(createSim({ levelId: level, difficulty, seed }), makeBot(bot));
    rows.push({ won: s.phase === 'won', lives: s.lives, max: s.maxLives, wave: s.waveIndex, total: s.totalWaves });
  }
  return { wins: rows.filter((r) => r.won).length, lives: rows.map((r) => r.lives), max: rows[0].max, waves: rows.map((r) => r.wave), total: rows[0].total };
}

export function levelReport(level) {
  const out = { level, balanced: {}, spam: {}, noUpgrades: null };
  for (const d of ['padawan', 'jedi', 'master']) out.balanced[d] = runSet(level, d, 'balanced');
  if (LEVEL_ORDER.indexOf(level) >= SPAM_FROM)
    for (const t of LEVELS[level].towers) out.spam[t] = runSet(level, 'jedi', `spam-${t}`);
  if (LEVELS[level].boss) out.noUpgrades = runSet(level, 'jedi', 'no-upgrades');
  return out;
}

function fmt(r) {
  return `${r.wins}/${SEEDS} (lives ${r.lives.join(' ')} / ${r.max})`;
}

function write(files) {
  const reps = files.map((f) => JSON.parse(readFileSync(f, 'utf8'))).sort((a, b) => LEVEL_ORDER.indexOf(a.level) - LEVEL_ORDER.indexOf(b.level));
  const fails = [];
  let md = '# Balance report\n\nGenerated by `node tools/sim/report.mjs` (headless sim, 5 seeds per row). Bots are a floor, not proof of good balance.\n\n';
  md += '## Balanced bot\n\n| Level | HP scale | Padawan | Jedi | Jedi Master |\n|---|---|---|---|---|\n';
  for (const r of reps) {
    const b = r.balanced;
    md += `| ${r.level} | ${STRENGTH[r.level]?.hp ?? 1} | ${fmt(b.padawan)} | ${fmt(b.jedi)} | ${fmt(b.master)} |\n`;
    if (b.padawan.wins < SEEDS) fails.push(`${r.level}: balanced wins only ${b.padawan.wins}/5 on Padawan`);
    if (b.jedi.wins < 1) fails.push(`${r.level}: balanced never wins on Jedi`);
  }
  md += '\n## Spam bots (Jedi, Geonosis 3 onward: every one must lose)\n\n| Level | ' + Object.keys(TOWERS).join(' | ') + ' |\n|---|' + Object.keys(TOWERS).map(() => '---').join('|') + '|\n';
  for (const r of reps) {
    if (!Object.keys(r.spam).length) continue;
    md += `| ${r.level} | ` + Object.keys(TOWERS).map((t) => {
      const x = r.spam[t];
      if (!x) return '-';
      if (x.wins) fails.push(`${r.level}: spam-${t} wins ${x.wins}/5`);
      return `${x.wins}/5, wave ${Math.max(...x.waves)}/${x.total}`;
    }).join(' | ') + ' |\n';
  }
  md += '\n## No-upgrades bot on boss levels (Jedi: must lose)\n\n| Level | Result |\n|---|---|\n';
  for (const r of reps) if (r.noUpgrades) {
    md += `| ${r.level} | ${r.noUpgrades.wins}/5 wins, best wave ${Math.max(...r.noUpgrades.waves)}/${r.noUpgrades.total} |\n`;
    if (r.noUpgrades.wins) fails.push(`${r.level}: no-upgrades wins ${r.noUpgrades.wins}/5`);
  }
  md += `\n## Gates\n\n${fails.length ? fails.map((f) => `- FAIL: ${f}`).join('\n') : '- All gates pass.'}\n`;
  const root = resolve(dirname(new URL(import.meta.url).pathname), '../..');
  writeFileSync(join(decodeURIComponent(root), 'BALANCE_REPORT.md'), md);
  console.log(fails.length ? `${fails.length} gate failures:\n` + fails.join('\n') : 'all gates pass');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = process.argv.slice(2);
  if (a[0] === '--write') write(a.slice(1));
  else console.log(JSON.stringify(levelReport(a[a.indexOf('--level') + 1])));
}
